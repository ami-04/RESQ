let LANG = (() => { try { return localStorage.getItem("resq.lang") === "de" ? "de" : "en"; } catch (e) { return "en"; } })();

function tr(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  for (const [k, v] of Object.entries(vars || {})) s = s.split("{" + k + "}").join(String(v));
  return s;
}
function trServer(msg) {
  if (LANG !== "de" || typeof msg !== "string") return msg;
  for (const [re, rep] of SERVER_DE) if (re.test(msg)) return msg.replace(re, rep);
  return msg;
}
function trReady(name) { return LANG === "de" ? (READY_DE[name] || name) : name; }

function applyStatic(root) {
  const r = root || document;
  r.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = tr(el.dataset.i18n); });
  r.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = tr(el.dataset.i18nHtml); });  // own strings only
  r.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = tr(el.dataset.i18nPh); });
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-lang]").forEach((b) => b.classList.toggle("active", b.dataset.lang === LANG));
}
function setLang(lang) {
  LANG = lang === "de" ? "de" : "en";
  try { localStorage.setItem("resq.lang", LANG); } catch (e) { /* storage unavailable: keep for this page only */ }
  applyStatic();
  document.dispatchEvent(new Event("langchange"));
}
document.querySelectorAll("[data-lang]").forEach((b) => b.addEventListener("click", () => setLang(b.dataset.lang)));
