$("btn-out").addEventListener("click", () => desk("out"));

const recent = [];
function addRecent(whatKey, id, res) {
  recent.unshift({ whatKey, id, res });
  recent.length = Math.min(recent.length, 8);
  renderRecent();
}
function renderRecent() {
  $("recent").replaceChildren(...recent.map(({ whatKey, id, res }) => h("li", {},
    h("span", {}, h("span", { class: "tag " + res.status }, tr("tag." + res.status)), " ", tr(whatKey), " ",
      h("b", {}, id), res.reason ? ` → ${res.reason}` : ""),
    h("span", { class: "t" }, hhmm(res.recorded_at) || "—"))));
}

