let busy = false;
async function desk(action) {
  const id = codeEl.value.trim();
  if (!id || busy) return;
  busy = true; $("btn-in").disabled = $("btn-out").disabled = true;
  const res = await api(action === "in" ? "/api/checkin" : "/api/checkout", { id });
  showFeedback($("feedback"), res);
  signal(res.status);
  addRecent(action === "in" ? "type.checkin" : "type.checkout", id, res);
  if (res.status !== "invalid") codeEl.value = "";
  selectedId = null;
  codeEl.focus(); codeEl.select();
  busy = false; $("btn-in").disabled = $("btn-out").disabled = false;
  refresh();
}
codeEl.addEventListener("keydown", (e) => {
  if (e.key === "Enter") { e.preventDefault(); desk(e.shiftKey ? "out" : "in"); }
});
