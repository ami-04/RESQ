/* RESQ operator UI — vanilla JS, no external dependencies, works fully offline.
   Texts come from i18n.js (tr = screen text, trServer = messages from the station app). */
"use strict";

const $ = (id) => document.getElementById(id);
function h(tag, attrs, ...kids) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (k === "class") el.className = v;
    else if (k.startsWith("data-")) el.setAttribute(k, v);
    else el[k] = v;
  }
  for (const kid of kids.flat()) {
    if (kid === null || kid === undefined) continue;
    el.append(kid instanceof Node ? kid : document.createTextNode(String(kid)));
  }
  return el;
}
/* replaceChildren, but skips empty parts (null / "" would otherwise show up as text) */
function setKids(el, ...kids) { el.replaceChildren(...kids.filter((k) => k !== null && k !== undefined && k !== "")); }
async function api(path, body) {
  const opt = body === undefined ? {} : {
    method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body),
  };
  try {
    const r = await fetch(path, opt);
    const data = await r.json().catch(() => ({ status: "error", message: `HTTP ${r.status}` }));
    appUp = true; badge();
    return data;
  } catch (e) {
    appUp = false; badge();
    return { status: "error", message: tr("app.down") };
  }
}
let appUp = true;
function badge() {
  $("rec-badge").textContent = tr(appUp ? "badge.ok" : "badge.bad");
  $("rec-badge").classList.toggle("bad", !appUp);
}
const hhmm = (iso) => (iso || "").slice(11, 19);

/* Anything drawn with render() is drawn again in the new language when the language changes. */
function render(el, fn) { el._render = fn; fn(); }

/* ------------------------------------------------------------------ feedback */
const LABEL = { success: "✔", rejected: "✖", invalid: "!", error: "!" };
function showFeedback(el, res) {
  render(el, () => {
    el.className = "feedback " + (res.status || "error");
    setKids(el,
      `${LABEL[res.status] || "!"} ${trServer(res.message || "")}`,
      res.seq ? h("small", {}, tr("fb.logged", { seq: res.seq, type: res.type, reason: res.reason ? " · " + res.reason : "", time: hhmm(res.recorded_at) }))
              : (res.status === "invalid" ? h("small", {}, tr("fb.nothing")) : null));
  });
}
function idle(el, key, vars) {
  render(el, () => { el.className = "feedback idle"; el.textContent = tr(key, vars); });
}

/* ------------------------------------------------------------------ flash + sound after each action
   success = green flash + high beep · rejected = red flash + low double tone · invalid (typo) = amber flash + short tick.
   Generated by the browser (Web Audio): no sound files, works offline. Mute button in the header. */
let soundOn = (() => { try { return localStorage.getItem("resq.sound") !== "off"; } catch (e) { return true; } })();
let audioCtx = null;
function tone(freq, start, dur, vol) {
  const o = audioCtx.createOscillator(), g = audioCtx.createGain();
  o.type = "sine"; o.frequency.value = freq;
  const t0 = audioCtx.currentTime + start;
  g.gain.setValueAtTime(0.0001, t0);
  g.gain.exponentialRampToValueAtTime(vol, t0 + 0.01);
  g.gain.exponentialRampToValueAtTime(0.0001, t0 + dur);
  o.connect(g).connect(audioCtx.destination);
  o.start(t0); o.stop(t0 + dur + 0.02);
}
function beep(status) {
  if (!soundOn) return;
  try {
    audioCtx = audioCtx || new (window.AudioContext || window.webkitAudioContext)();
    if (audioCtx.state === "suspended") audioCtx.resume();
    if (status === "success") tone(1320, 0, 0.12, 0.25);
    else if (status === "rejected") { tone(220, 0, 0.16, 0.35); tone(220, 0.22, 0.16, 0.35); }
    else tone(600, 0, 0.05, 0.15);
  } catch (e) { /* no audio available: the flash still works */ }
}
function flash(status) {
  const el = $("flash");
  el.className = "flash";
  void el.offsetWidth;                       // restart the animation if two results come quickly
  el.className = "flash show " + (status === "success" ? "ok" : status === "rejected" ? "bad" : "warn");
}
function signal(status) { flash(status); beep(status); }
function renderSoundBtn() {
  const b = $("sound-btn");
  b.textContent = soundOn ? "🔊" : "🔇";
  b.title = tr(soundOn ? "sound.on" : "sound.off");
  b.setAttribute("aria-label", b.title);
  b.classList.toggle("off", !soundOn);
}
$("sound-btn").addEventListener("click", () => {
  soundOn = !soundOn;
  try { localStorage.setItem("resq.sound", soundOn ? "on" : "off"); } catch (e) { /* keep for this page */ }
  renderSoundBtn();
  if (soundOn) beep("success");              // short test beep so the operator hears the volume
  codeEl.focus();
});

