async function runFinder(q) {
  lastQuery = q;
  const d = await api(`/api/finder?q=${encodeURIComponent(q)}&role=${encodeURIComponent(fRole)}`);
  if (!d.results) { showFeedback($("f-summary"), d); return; }
  lastFinder = d;
  renderFinder();
}
function renderFinder() {
  const d = lastFinder;
  if (!d) { idle($("f-summary"), "finder.start"); return; }
  const q = d.query;
  render($("f-summary"), () => {
    const el = $("f-summary");
    el.className = "feedback " + (d.count || !q ? "success" : "invalid");
    const head = !q ? tr("finder.all.n", { n: d.count })
      : d.count ? tr("finder.found", { n: d.count, q }) : tr("finder.none", { q });
    const groups = d.groups.map((g) => d.group_labels[g][LANG] || d.group_labels[g].en);
    setKids(el, head + (d.role ? ` · ${tr("finder.rolefilter", { role: d.role })}` : ""),
      groups.length ? h("small", {}, tr("finder.also", { groups: groups.join(" · ") })) : null,
      d.off_site_count ? h("small", {}, tr("finder.offsite", { n: d.off_site_count })) : null);
  });
  $("f-results").replaceChildren(...d.results.map((p) => h("tr", {},
    h("td", { class: "mono" }, p.id), h("td", {}, p.name || "—"),
    h("td", {}, h("span", { class: "dot " + p.role }), p.role),
    h("td", {}, p.skill || "—"),
    h("td", {}, h("span", { class: "tag " + (p.claimed ? "claimed" : "listed") }, tr(p.claimed ? "finder.claimed" : "finder.listed"))),
    h("td", { class: "mono" }, hhmm(p.since).slice(0, 5)))));
}

/* ------------------------------------------------------------------ dashboard / header */
function bars(el, obj, cls) {
  const entries = Object.entries(obj);
  const max = Math.max(1, ...entries.map(([, v]) => v));
  el.replaceChildren(...(entries.length ? entries.map(([k, v]) => h("div", { class: "bar" },
    h("span", {}, k), h("div", { class: "track" }, h("div", { class: `fill ${cls || k} w${Math.round((v / max) * 10) * 10}` })),
    h("b", {}, v))) : [h("div", { class: "muted" }, tr("none.yet"))]));
}
let activeCache = [];
function renderActive() {
  const f = $("active-filter").value.trim().toUpperCase();
  const list = activeCache.filter((p) => !f || p.id.includes(f) || (p.name || "").toUpperCase().includes(f));
  $("active-list").replaceChildren(...list.map((p) => {
    const li = h("li", { class: "pick" + (p.id === selectedId ? " selected" : ""), tabIndex: 0, title: tr("desk.pick.title") },
      h("span", {}, h("span", { class: "dot " + p.role }), h("span", { class: "id" }, p.id), p.name ? ` ${p.name}` : ""),
      h("span", { class: "muted" }, hhmm(p.since).slice(0, 5)));
    li.addEventListener("click", () => pickForCheckout(p.id));
    li.addEventListener("keydown", (e) => { if (e.key === "Enter") { e.preventDefault(); pickForCheckout(p.id); } });
    return li;
  }));
}
/* Click a person who is on site -> their ID goes into the code field and the row is highlighted.
   Nothing is written yet: the operator confirms with "Check out" or Shift+Enter,
   so a mis-click never checks anyone out. */
function pickForCheckout(id) {
  selectedId = id;
  codeEl.value = id;
  idle($("feedback"), "desk.pick", { id });
  renderActive();
  codeEl.focus(); codeEl.select();
}
$("active-filter").addEventListener("input", renderActive);
$("active-filter").addEventListener("keydown", (e) => {
  /* Filter, then Enter: if exactly one person matches, select them for check-out. */
  if (e.key !== "Enter") return;
  const f = $("active-filter").value.trim().toUpperCase();
  const m = activeCache.filter((p) => p.id.includes(f) || (p.name || "").toUpperCase().includes(f));
  if (f && m.length === 1) { e.preventDefault(); $("active-filter").value = ""; pickForCheckout(m[0].id); }
});

